def main():
    db = sqlite3.connect(DB_PATH)
    db.row_factory = sqlite3.Row

    # Ensure table exists
    db.execute("""
        CREATE TABLE IF NOT EXISTS wr_advanced_career (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            player_id INTEGER REFERENCES players(id) UNIQUE,
            qbr_when_targeted REAL, adot REAL, yprr REAL,
            zone_yprr REAL, man_yprr REAL,
            first_down_rate REAL, td_per_route REAL,
            first_down_per_target REAL, td_per_target REAL,
            yac_per_rec REAL, air_yards_per_rec REAL,
            catch_rate REAL, target_rate REAL, open_target_rate REAL,
            drop_rate REAL, contested_catch_rate REAL, forced_mtf_pct REAL,
            yac_rate REAL, air_yards_rate REAL,
            wide_rate REAL, slot_rate REAL,
            data_source TEXT DEFAULT 'manual_2026',
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)

    hit = 0
    miss = 0

    for row in RECORDS:
        slug = row[0]
        values = row[1:]

        player = db.execute("SELECT id FROM players WHERE slug = ?", (slug,)).fetchone()
        if not player:
            print(f"  MISS  {slug}")
            miss += 1
            continue

        pid = player["id"]
        set_clauses = ", ".join(f"{c} = ?" for c in COLS)
        params = list(values) + [pid]

        if DRY_RUN:
            print(f"  DRY   {slug} → player_id={pid}")
        else:
            db.execute(f"""
                INSERT INTO wr_advanced_career (player_id, {', '.join(COLS)})
                VALUES (?, {', '.join('?' for _ in COLS)})
                ON CONFLICT(player_id) DO UPDATE SET
                    {set_clauses},
                    updated_at = CURRENT_TIMESTAMP
            """, [pid] + list(values) + list(values))
            print(f"  OK    {slug}")

        hit += 1

    if not DRY_RUN:
        db.commit()

    db.close()
    print(f"\nDone: {hit} seeded, {miss} not found")


if __name__ == "__main__":
    main()
